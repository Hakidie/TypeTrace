import { describe, expect, it } from 'vitest';
import { AVATAR_SLOTS } from '../../src/data/avatar-items';

const SLOTS = ['skin', 'face', 'hair', 'top', 'bottom', 'shoes', 'headwear', 'accessory', 'back', 'effect'];

describe('AVATAR_SLOTS (generated by minigame-sprites/build-layers.mjs)', () => {
  it('lists every slot with at least one item', () => {
    expect(Object.keys(AVATAR_SLOTS).sort()).toEqual([...SLOTS].sort());
    for (const slot of SLOTS) {
      const items: readonly string[] = AVATAR_SLOTS[slot as keyof typeof AVATAR_SLOTS];
      expect(items.length, slot).toBeGreaterThan(0);
      expect(new Set(items).size, slot).toBe(items.length);
    }
  });

  it('has every item of the default avatar', () => {
    expect(AVATAR_SLOTS.skin).toContain('peach');
    expect(AVATAR_SLOTS.face).toContain('classic');
    expect(AVATAR_SLOTS.hair).toContain('short-brown');
    expect(AVATAR_SLOTS.top).toContain('red');
    expect(AVATAR_SLOTS.bottom).toContain('navy');
    expect(AVATAR_SLOTS.shoes).toContain('sneakers-brown');
  });

  it('keeps the slot of each kind of item apart', () => {
    expect(AVATAR_SLOTS.headwear).toContain('crown');
    expect(AVATAR_SLOTS.hair).not.toContain('crown');
    expect(AVATAR_SLOTS.top).toContain('dress-sailor-navy');
    expect(AVATAR_SLOTS.shoes).toContain('boots-black');
  });
});
